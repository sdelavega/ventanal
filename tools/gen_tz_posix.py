"""Generate firmware/common/tz_posix.h: IANA zone -> POSIX TZ string.

The setup portal resolves a US ZIP to coordinates, Open-Meteo names the IANA
zone there, and the board stores the POSIX rule that newlib's TZ understands.
The rule is the footer of each zone's TZif (v2+) file. Only the US zones and
territories a US ZIP can land in are listed, which keeps the table small and
keeps the output stable across machines' tzdata versions.

Run: python3 tools/gen_tz_posix.py [--check]
"""
import argparse
import sys
import zoneinfo
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'firmware/common/tz_posix.h'

ZONES = sorted([
    # zone.tab entries for US, and the territories with US ZIP codes.
    'America/Adak', 'America/Anchorage', 'America/Boise', 'America/Chicago',
    'America/Denver', 'America/Detroit', 'America/Indiana/Indianapolis',
    'America/Indiana/Knox', 'America/Indiana/Marengo', 'America/Indiana/Petersburg',
    'America/Indiana/Tell_City', 'America/Indiana/Vevay', 'America/Indiana/Vincennes',
    'America/Indiana/Winamac', 'America/Juneau', 'America/Kentucky/Louisville',
    'America/Kentucky/Monticello', 'America/Los_Angeles', 'America/Menominee',
    'America/Metlakatla', 'America/New_York', 'America/Nome',
    'America/North_Dakota/Beulah', 'America/North_Dakota/Center',
    'America/North_Dakota/New_Salem', 'America/Phoenix', 'America/Puerto_Rico',
    'America/Sitka', 'America/St_Thomas', 'America/Yakutat', 'Pacific/Guam',
    'Pacific/Honolulu', 'Pacific/Pago_Pago', 'Pacific/Saipan',
    # Fallbacks Open-Meteo can name for an unzoned point.
    'Etc/UTC', 'GMT',
])


def tzif_path(name):
    for base in zoneinfo.TZPATH:
        path = Path(base) / name
        if path.is_file():
            return path
    try:
        import importlib.resources
        return importlib.resources.files('tzdata.zoneinfo').joinpath(*name.split('/'))
    except ModuleNotFoundError:
        raise SystemExit(f'No TZif data for {name}: install tzdata')


def posix_rule(name):
    data = tzif_path(name).read_bytes()
    if data[:4] != b'TZif' or data[4:5] not in (b'2', b'3', b'4'):
        raise SystemExit(f'{name}: not a TZif v2+ file')
    footer = data.rstrip(b'\n').rsplit(b'\n', 1)[-1].decode('ascii')
    if not footer or '"' in footer or '\\' in footer:
        raise SystemExit(f'{name}: unusable POSIX footer {footer!r}')
    return footer


def render():
    rows = '\n'.join(f'    {{"{name}", "{posix_rule(name)}"}},' for name in ZONES)
    return f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 Stephen de la Vega
// Generated by tools/gen_tz_posix.py; do not edit.
#pragma once

#include <cstring>

struct TzPosix {{
    const char* iana;
    const char* posix;
}};

// Sorted by IANA name for binary search.
inline constexpr TzPosix tzPosixTable[] = {{
{rows}
}};

// The POSIX TZ rule for an IANA zone, or nullptr when it isn't listed.
inline const char* posixForIana(const char* iana) {{
    size_t lo = 0, hi = sizeof tzPosixTable / sizeof tzPosixTable[0];
    while (lo < hi) {{
        const size_t mid = (lo + hi) / 2;
        const int order = strcmp(tzPosixTable[mid].iana, iana);
        if (!order) return tzPosixTable[mid].posix;
        if (order < 0) lo = mid + 1;
        else hi = mid;
    }}
    return nullptr;
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the header is stale')
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit(f'Stale generated file: {OUT.relative_to(ROOT)} (run tools/gen_tz_posix.py)')
        return
    OUT.write_text(text)


if __name__ == '__main__':
    main()
