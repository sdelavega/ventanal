"""Generate LCD-only 4-bit coverage fonts from repository SIL OFL TTFs.

Run: server/.venv/bin/python tools/aa_fonts.py [--check]
Only used sizes are included; per-glyph advances match the original readouts.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
FONTS = [
    ('SidebarLabel','antonio','Antonio-Bold',13),
    ('ClockTime','antonio','Antonio-Bold',19),
    ('ClockDate','antonio','Antonio-Regular',13),
    ('ArtTime','inter','Inter-Bold',20),
    ('ArtDate','inter','Inter-Medium',11),
    ('StatusFont','antonio','Antonio-Bold',28),
    ('WaitingTitle','inter','Inter-Medium',21),
    ('WaitingBody','inter','Inter-Medium',17),
]

def generate():
    out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
           '// Copyright (C) 2026 Stephen de la Vega',
           '// Generated by tools/aa_fonts.py; fonts: server/src/ventanal/fonts (SIL OFL).',
           '#pragma once', '#include "aafont.h"']
    total = 0
    for name,family,weight,size in FONTS:
        face = ImageFont.truetype(str(ROOT/f'server/src/ventanal/fonts/{family}/{weight}.ttf'),size)
        bits,glyphs = [],[]
        for code in range(32,127):
            c=chr(code)
            x0,y0,x1,y1=face.getbbox(c,anchor='ls')
            w,h=x1-x0,y1-y0
            mask=Image.new('L',(max(1,w),max(1,h)))
            ImageDraw.Draw(mask).text((-x0,-y0),c,font=face,fill=255,anchor='ls')
            alpha=[(mask.getpixel((x,y))*15+127)//255 for y in range(h) for x in range(w)]
            glyphs.append(f'{{{len(bits)},{w},{h},{round(face.getlength(c))},{x0},{y0}}}')
            bits.extend((alpha[i]<<4)|(alpha[i+1] if i+1<len(alpha) else 0) for i in range(0,len(alpha),2))
        total+=len(bits)
        out += [f'// {weight}, {size} px; {len(bits)} bitmap bytes.',
                f'const uint8_t {name}Bits[] = {{'+','.join(map(str,bits))+'};',
                f'const lcd::AAGlyph {name}Glyphs[] = {{'+','.join(glyphs)+'};',
                f'const lcd::AAFont {name} = {{{name}Bits,{name}Glyphs,32,126,{size+4}}};']
    print(f'AA fonts: {total} bitmap bytes, {len(FONTS)} used faces/sizes')
    return ('\n'.join(out)+'\n').encode()

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=ROOT/'firmware/lcd43b/readout_fonts.h'
    data=generate()
    if args.check:
        if path.read_bytes()!=data:
            raise SystemExit('Stale readout_fonts.h')
    else:
        path.write_bytes(data)
