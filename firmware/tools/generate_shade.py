"""Reproduce the periodic 64x64 void-and-cluster threshold and Gaussian LUT."""
from pathlib import Path
from math import erf, sqrt
import numpy as np

size = 64
rng = np.random.default_rng(20261116)
pattern = np.zeros(size * size, dtype=bool)
pattern[rng.choice(size * size, size * size // 2, replace=False)] = True
pattern = pattern.reshape(size, size)
y, x = np.indices((size, size))
x = np.minimum(x, size - x)
y = np.minimum(y, size - y)
kernel = np.exp(-(x*x + y*y) / (2 * 1.5**2))
def density(bits):
    return np.fft.ifft2(np.fft.fft2(bits) * np.fft.fft2(kernel)).real

def shift(index):
    return np.roll(kernel, np.unravel_index(index, pattern.shape), axis=(0, 1))

energy = density(pattern)
for iteration in range(20000):
    cluster = np.argmax(np.where(pattern, energy, -np.inf))
    pattern.flat[cluster] = False
    energy -= shift(cluster)
    void = np.argmin(np.where(~pattern, energy, np.inf))
    pattern.flat[void] = True
    energy += shift(void)
    if cluster == void:
        break
else:
    raise RuntimeError('void/cluster relaxation did not converge')
seed = pattern.copy()
ranks = np.empty_like(pattern, dtype=np.uint16)
for rank in range(size*size//2 - 1, -1, -1):
    cluster = np.argmax(np.where(pattern, energy, -np.inf))
    ranks.flat[cluster] = rank
    pattern.flat[cluster] = False
    energy -= shift(cluster)
pattern = seed.copy()
energy = density(pattern)
for rank in range(size*size//2, size*size):
    void = np.argmin(np.where(~pattern, energy, np.inf))
    ranks.flat[void] = rank
    pattern.flat[void] = True
    energy += shift(void)
assert len(np.unique(ranks)) == size*size
# Empirical panel-lightness fit to pre-quantization mock shade (Hunters,
# task-gamut calibrated palette). Geometry stays fixed; only opacity changes.
profile = [round(228 * .5 * (1 - erf((d - 4) / (13 * sqrt(2))))) for d in range(-64, 65)]
header = '''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 Stephen de la Vega
// Generated by firmware/tools/generate_shade.py; seed 20261116, sigma 1.5.
#pragma once
#include <cstdint>
'''
def array(name, values):
    return f'constexpr uint8_t {name}[] = {{\n' + ''.join(
        '    ' + ','.join(str(int(v)) for v in values[i:i+32]) + ',\n'
        for i in range(0, len(values), 32)) + '};\n'
Path('firmware/ventanal/shade_tables.h').write_text(header + array('shadeEdge', profile) +
    array('shadeBlueNoise', (ranks // 16).ravel()))
print(f'generated balanced 4096-rank void-and-cluster table; relaxed in {iteration+1} swaps')
