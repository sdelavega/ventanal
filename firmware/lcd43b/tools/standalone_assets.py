"""Fonts and frame chrome for the board's own standalone screens.

The board must draw the same pixels the server's Pillow code draws. Measured
against Pillow 13 on the Antonio faces, this matches exactly:
  * each glyph's 8-bit coverage, rendered at a whole-pixel origin (stored
    here as 4-bit coverage, <= 8/255 error),
  * pen advances in 1/64 px (FreeType 26.6) plus the font's kerning pairs,
    rounding the pen to the nearest pixel at every glyph,
  * anchors snapped to whole pixels: 'ms' starts at x - (L//2 + 32)//64,
    'rs' at (64x - L + 32)//64, where L is the width in 1/64 px.
The frame (elbows, bars, sidebar blocks; labels excluded) is stored as
exact anti-aliased RGB565 scanline spans, as for the Settings page.

Run: server/.venv/bin/python firmware/lcd43b/tools/standalone_assets.py [--check]
"""
import argparse
import sys
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'server/src'))
from ventanal.devices.lcd_lcars import LCD_COLOURS, draw_lcd_frame  # noqa: E402
from ventanal.weather.data import WMO_LONG, WMO_SHORT  # noqa: E402
from ventanal.devices.lcd_weather import SECTIONS as WEATHER_SECTIONS  # noqa: E402
from ventanal.devices.lcd_solar import SECTIONS as SOLAR_SECTIONS  # noqa: E402

FONT_DIR = ROOT / 'server/src/ventanal/fonts'
TEXT = ''.join(chr(c) for c in range(32, 127)) + '°·…≈Å–'
DIGITS = '0123456789-°…'
NUMBER = '0123456789.-…'
# Art credits name artists and places from everywhere: Latin-1 and Latin
# Extended-A, plus typographic punctuation.
LATIN = (''.join(chr(c) for c in range(32, 127)) + ''.join(chr(c) for c in range(0xa0, 0x180))
         + '·…–—‘’“”′″')

# (C++ name, file, pixel size, characters): only the faces and sizes the
# standalone renderers use (server/src/ventanal/devices/lcd_weather.py).
FACES = [
    ('AntonioBold30', 'antonio/Antonio-Bold', 30, TEXT),
    ('AntonioBold108', 'antonio/Antonio-Bold', 108, DIGITS),
    ('AntonioBold24', 'antonio/Antonio-Bold', 24, TEXT),
    ('AntonioBold19', 'antonio/Antonio-Bold', 19, TEXT),
    ('AntonioBold27', 'antonio/Antonio-Bold', 27, TEXT),
    ('AntonioBold16', 'antonio/Antonio-Bold', 16, TEXT),
    ('AntonioBold13', 'antonio/Antonio-Bold', 13, TEXT),
    ('AntonioBold12', 'antonio/Antonio-Bold', 12, TEXT),
    ('Antonio24', 'antonio/Antonio-Regular', 24, TEXT),
    ('Antonio17', 'antonio/Antonio-Regular', 17, TEXT),
    ('Antonio16', 'antonio/Antonio-Regular', 16, TEXT),
    ('Antonio14', 'antonio/Antonio-Regular', 14, TEXT),
    ('Antonio13', 'antonio/Antonio-Regular', 13, TEXT),
    ('Antonio12', 'antonio/Antonio-Regular', 12, TEXT),
    # The solar screen (devices/lcd_solar.py render_lcd_solar).
    ('AntonioBold90', 'antonio/Antonio-Bold', 90, NUMBER),
    ('AntonioBold34', 'antonio/Antonio-Bold', 34, TEXT),
    ('AntonioBold18', 'antonio/Antonio-Bold', 18, TEXT),
    ('AntonioBold17', 'antonio/Antonio-Bold', 17, TEXT),
    ('Antonio18', 'antonio/Antonio-Regular', 18, TEXT),
    ('Antonio15', 'antonio/Antonio-Regular', 15, TEXT),
    ('Antonio11', 'antonio/Antonio-Regular', 11, TEXT),
    # Art credits (devices/lcd43b.py render_art).
    ('InterBold12', 'inter/Inter-Bold', 12, LATIN),
    ('Inter11', 'inter/Inter-Medium', 11, LATIN),
]

HEADER = ['// SPDX-License-Identifier: GPL-3.0-or-later',
          '// Copyright (C) 2026 Stephen de la Vega']


def glyph_mask(face, c):
    x0, y0, x1, y1 = face.getbbox(c, anchor='ls')
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return x0, y0, 0, 0, []
    mask = Image.new('L', (w, h))
    ImageDraw.Draw(mask).text((-x0, -y0), c, font=face, fill=255, anchor='ls')
    return x0, y0, w, h, [(mask.getpixel((x, y)) * 15 + 127) // 255 for y in range(h) for x in range(w)]


def kern64(face, a, b):
    return round((face.getlength(a + b) - face.getlength(a) - face.getlength(b)) * 64)


def fonts_header():
    out = HEADER + ['// Generated by firmware/lcd43b/tools/standalone_assets.py; fonts: '
                    'server/src/ventanal/fonts (SIL OFL).', '#pragma once', '#include "text.h"',
                    'namespace lcd::local {']
    total = 0
    for name, file, size, chars in FACES:
        face = ImageFont.truetype(str(FONT_DIR / f'{file}.ttf'), size)
        weight = file.split('/')[-1]
        chars = ''.join(sorted(set(chars)))
        bits, glyphs = [], []
        for c in chars:
            x0, y0, w, h, alpha = glyph_mask(face, c)
            if not -128 <= x0 <= 127 or not -128 <= y0 <= 127 or w > 255 or h > 255:
                raise SystemExit(f'{name}: glyph {c!r} out of range')
            glyphs.append(f'{{{len(bits)},{w},{h},{x0},{y0},{round(face.getlength(c) * 64)}}}')
            bits.extend((alpha[i] << 4) | (alpha[i + 1] if i + 1 < len(alpha) else 0)
                        for i in range(0, len(alpha), 2))
        kerns = [(ord(a), ord(b), k) for a in chars for b in chars if (k := kern64(face, a, b))]
        total += len(bits) + 8 * len(glyphs) + 6 * len(kerns)
        out += [f'// {weight}, {size} px: {len(chars)} glyphs, {len(bits)} bitmap bytes, {len(kerns)} kerning pairs.',
                f'inline constexpr uint8_t {name}Bits[] = {{' + ','.join(map(str, bits)) + '};',
                f'inline constexpr uint16_t {name}Codes[] = {{' + ','.join(str(ord(c)) for c in chars) + '};',
                f'inline constexpr TextGlyph {name}Glyphs[] = {{' + ','.join(glyphs) + '};',
                f'inline constexpr KernPair {name}Kerns[] = {{'
                + (','.join(f'{{{a},{b},{k}}}' for a, b, k in kerns) or '{0,0,0}') + '};',
                f'inline constexpr TextFace {name} = {{{name}Bits,{name}Codes,{name}Glyphs,{len(chars)},'
                f'{name}Kerns,{len(kerns)}}};']
    out += ['}  // namespace lcd::local']
    print(f'standalone fonts: {total} bytes, {len(FACES)} faces')
    return ('\n'.join(out) + '\n').encode()


def rgb565(rgb):
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def chrome_spans(image):
    spans = []
    for y in range(480):
        for colour, group in groupby(range(800), key=lambda x: rgb565(image.getpixel((x, y)))):
            xs = list(group)
            if colour:
                spans.append(f'    {{{y},{xs[0]},{xs[-1]},0x{colour:04x}}},')
    return spans


def chrome_header():
    out = HEADER + ['// Generated by firmware/lcd43b/tools/standalone_assets.py: exact AA RGB565 scanlines',
                    '// of the standalone screens\' frames (labels are drawn by the board).',
                    '#pragma once', '#include "../lcars_geometry.h"', 'namespace lcd::local {',
                    'struct FrameSection { int16_t y, h; uint16_t labelInk; };']
    weather = Image.new('RGB', (800, 480))
    draw_lcd_frame(weather, [(y, h, colour, '') for y, h, colour, _ in WEATHER_SECTIONS],
                   accent='violet', clock_block='orange')
    out += ['inline constexpr ChromeSpan WEATHER_CHROME[] = {'] + chrome_spans(weather) + ['};']
    out += ['// The sidebar blocks: labels are black, white on gray (draw_lcd_frame).',
            'inline constexpr FrameSection WEATHER_SECTIONS[] = {']
    out += [f'    {{{y},{h},0x{0xffff if colour == "gray" else 0:04x}}},' for y, h, colour, _ in WEATHER_SECTIONS]
    out += ['};']
    solar = Image.new('RGB', (800, 480))
    draw_lcd_frame(solar, [(y, h, colour, '') for y, h, colour, _ in SOLAR_SECTIONS], clock_block='orange')
    out += ['inline constexpr ChromeSpan SOLAR_CHROME[] = {'] + chrome_spans(solar) + ['};']
    out += ['inline constexpr FrameSection SOLAR_SECTIONS[] = {']
    out += [f'    {{{y},{h},0x{0xffff if colour == "gray" else 0:04x}}},' for y, h, colour, _ in SOLAR_SECTIONS]
    out += ['};', '// The server\'s LCD palette (devices/lcd_lcars.LCD_COLOURS), 0xRRGGBB.', 'namespace colour {']
    for name, value in sorted({**LCD_COLOURS, 'white': '#ffffff', 'black': '#000000'}.items()):
        out.append(f'inline constexpr uint32_t {name} = 0x{value.lstrip("#").lower()};')
    out += ['}  // namespace colour',
            '// Weather code names (weather/data.py WMO_LONG / WMO_SHORT).',
            'struct WmoName { uint8_t code; const char* longName; const char* shortName; };',
            'inline constexpr WmoName WMO_NAMES[] = {']
    for code in sorted(set(WMO_LONG) | set(WMO_SHORT)):
        out.append(f'    {{{code},"{WMO_LONG.get(code, "Unknown")}","{WMO_SHORT.get(code, "UNKNOWN")}"}},')
    out += ['};', '}  // namespace lcd::local']
    return ('\n'.join(out) + '\n').encode()


def seasons_header():
    """The public example's art seasons (server/ventanal.example.toml)."""
    import tomllib
    seasons = tomllib.loads((ROOT / 'server/ventanal.example.toml').read_text())['art']['seasons']
    out = HEADER + ['// Generated by firmware/lcd43b/tools/standalone_assets.py from server/ventanal.example.toml.',
                    '#pragma once', '#include <cstdint>', 'namespace lcd::local {',
                    'struct ArtSeason { const char* name; uint8_t startMonth, startDay, endMonth, endDay;',
                    '                   const char* const* terms; uint8_t termCount; };']
    for i, s in enumerate(seasons):
        terms = ', '.join('"' + t.replace('"', '\\"') + '"' for t in s['terms'])
        out.append(f'inline constexpr const char* ART_SEASON_TERMS_{i}[] = {{{terms}}};')
    out.append('inline constexpr ArtSeason ART_SEASONS[] = {')
    for i, s in enumerate(seasons):
        (sm, sd), (em, ed) = (map(int, s['start'].split('-')), map(int, s['end'].split('-')))
        out.append(f'    {{"{s["name"]}", {sm}, {sd}, {em}, {ed}, ART_SEASON_TERMS_{i}, {len(s["terms"])}}},')
    out += ['};', '}  // namespace lcd::local']
    return ('\n'.join(out) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if a generated header is stale')
    args = parser.parse_args()
    for path, data in ((ROOT / 'firmware/lcd43b/local/standalone_fonts.h', fonts_header()),
                       (ROOT / 'firmware/lcd43b/local/standalone_chrome.h', chrome_header()),
                       (ROOT / 'firmware/lcd43b/local/standalone_seasons.h', seasons_header())):
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                sys.exit(f'Stale generated file: {path.relative_to(ROOT)}')
        else:
            path.write_bytes(data)


if __name__ == '__main__':
    main()
