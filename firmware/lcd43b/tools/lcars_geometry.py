"""Bake PIL's non-antialiased elbow raster and independent Settings fixture.

Run with server/.venv/bin/python firmware/lcd43b/tools/lcars_geometry.py.
The firmware stores inclusive scanline spans instead of reimplementing PIL's
polygon edge rounding. The fixture is a separate render of draw_lcd_frame,
with labels excluded (GFX uses monochrome glyphs); colours are RGB565.
"""
from pathlib import Path
import sys
import struct
import argparse
from itertools import groupby
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'server/src'))
from ventanal.devices.lcd_lcars import draw_lcd_frame
from ventanal.weather.lcars import elbow

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail on stale generated files')
args = parser.parse_args()

def emit(path, data):
    if args.check:
        if path.read_bytes() != data:
            raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
    else:
        path.write_bytes(data)

out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
       '// Copyright (C) 2026 Stephen de la Vega',
       '// Generated by tools/lcars_geometry.py: exact PIL inclusive scanlines.',
       '#pragma once', 'namespace lcd {',
       'struct ChromeSpan { int y, left, right; };',
       'constexpr ChromeSpan LCARS_ELBOWS[] = {']
im = Image.new('RGB', (800, 480))
d = ImageDraw.Draw(im)
elbow(d, 0, 0, 530, 56, 26, 100, 44, 30, 'white', False)
elbow(d, 0, 430, 800, 50, 22, 100, 44, 28, 'white', True)
# Include the right cap's PIL rounding too.
d.rounded_rectangle((752, 0, 799, 25), radius=13, fill='white')
d.rectangle((752, 0, 775, 25), fill='white')
for y in range(480):
    for value, group in groupby(range(800), key=lambda x: im.getpixel((x,y)) != (0,0,0)):
        xs = list(group)
        if value:
            out.append(f'    {{{y},{xs[0]},{xs[-1]}}},')
out += ['};', '} // namespace lcd']
emit(ROOT/'firmware/lcd43b/lcars_geometry.h', ('\n'.join(out)+'\n').encode())
im = Image.new('RGB', (800,480))
draw_lcd_frame(im, [(60,120,'violet',''), (184,100,'sky',''), (288,138,'gold','')])
# RLE count/colour pairs, little endian uint16; includes every black pixel.
words = [((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in (im.getpixel((x,y)) for y in range(480) for x in range(800))]
packed = bytearray()
for colour, group in groupby(words):
    count = sum(1 for _ in group)
    while count:
        n = min(count,65535)
        packed += struct.pack('<HH', n, colour)
        count -= n
emit(ROOT/'firmware/test/fixtures/lcd43b-settings-chrome.rle', packed)
print(f'Settings fixture: {len(packed)} bytes, 384000 RGB565 pixels')
