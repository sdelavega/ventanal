"""Bake LCD anti-aliased RGB565 chrome and independent Settings fixture.

Run with server/.venv/bin/python firmware/lcd43b/tools/lcars_geometry.py.
The firmware stores inclusive scanline spans instead of reimplementing PIL's
polygon edge rounding. The fixture is a separate render of draw_lcd_frame,
with labels excluded; colours include anti-aliased RGB565 edges.
"""
from pathlib import Path
import sys
import struct
import argparse
from itertools import groupby
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'server/src'))
from ventanal.devices.lcd_lcars import draw_lcd_frame


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail on stale generated files')
args = parser.parse_args()

def emit(path, data):
    if args.check:
        if path.read_bytes() != data:
            raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
    else:
        path.write_bytes(data)

# Authoritative Settings sidebar layout; emitted below for firmware labels.
SETTINGS_SECTIONS = [(60,120,'violet','DISPLAY'),
                     (184,100,'sky','POWER'),
                     (288,138,'gold','SCREENS')]
chrome_sections = [(y,h,colour,'') for y,h,colour,label in SETTINGS_SECTIONS]

im = Image.new('RGB', (800,480))
draw_lcd_frame(im, chrome_sections)
out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
       '// Copyright (C) 2026 Stephen de la Vega',
       '// Generated by tools/lcars_geometry.py: exact AA RGB565 scanlines.',
       '#pragma once', '#include <cstdint>', 'namespace lcd {',
       'struct ChromeSpan { int16_t y, left, right; uint16_t colour; };',
       'constexpr ChromeSpan LCARS_CHROME[] = {']
def rgb565(rgb):
    r,g,b=rgb
    return ((r>>3)<<11)|((g>>2)<<5)|(b>>3)
for y in range(480):
    for colour, group in groupby(range(800), key=lambda x: rgb565(im.getpixel((x,y)))):
        xs=list(group)
        if colour:
            out.append(f'    {{{y},{xs[0]},{xs[-1]},0x{colour:04x}}},')
out += ['};', 'struct SettingsSection { int y,h; const char* label; };',
        'constexpr SettingsSection SETTINGS_SECTIONS[] = {']
for y,h,colour,label in SETTINGS_SECTIONS:
    out.append(f'    {{{y},{h},"{label}"}},')
out += ['};', '} // namespace lcd']
emit(ROOT/'firmware/lcd43b/lcars_geometry.h', ('\n'.join(out)+'\n').encode())
# Independent full render for the host fixture, rather than decoding the spans.
im = Image.new('RGB', (800,480))
draw_lcd_frame(im, chrome_sections)
# RLE count/colour pairs, little endian uint16; includes every black pixel.
words = [((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in (im.getpixel((x,y)) for y in range(480) for x in range(800))]
packed = bytearray()
for colour, group in groupby(words):
    count = sum(1 for _ in group)
    while count:
        n = min(count,65535)
        packed += struct.pack('<HH', n, colour)
        count -= n
emit(ROOT/'firmware/test/fixtures/lcd43b-settings-chrome.rle', packed)
print(f'Settings fixture: {len(packed)} bytes, 384000 RGB565 pixels')
