"""Regenerate readout_fonts.h using Pillow and repository OFL font sources."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
base = Path(__file__).resolve().parents[3]
out = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Copyright (C) 2026 Stephen de la Vega', '// Generated by tools/readout_fonts.py; Inter/Antonio under SIL OFL (server font directories).', '#pragma once', '#include "gfxfont.h"']
for name, family, weight, size in [('SidebarLabel','antonio','Antonio-Bold',13), ('ClockTime','antonio','Antonio-Bold',19), ('ClockDate','antonio','Antonio-Regular',13), ('ArtTime','inter','Inter-Bold',20), ('ArtDate','inter','Inter-Medium',11)]:
    font = ImageFont.truetype(str(base / f'server/src/ventanal/fonts/{family}/{weight}.ttf'), size)
    bits, glyphs = [], []
    for code in range(32,127):
        c=chr(code); x0,y0,x1,y1=font.getbbox(c,anchor='ls'); w,h=x1-x0,y1-y0
        im=Image.new('1',(max(1,w),max(1,h)))
        ImageDraw.Draw(im).text((-x0,-y0),c,font=font,fill=1,anchor='ls')
        packed=[im.getpixel((x,y)) for y in range(h) for x in range(w)]
        glyphs.append(f'{{{len(bits)},{w},{h},{round(font.getlength(c))},{x0},{y0}}}')
        for i in range(0,len(packed),8):
            bits.append(sum(v<<(7-j) for j,v in enumerate(packed[i:i+8])))
    out += [f'const uint8_t {name}Bits[] PROGMEM = {{'+','.join(map(str,bits))+'};', f'const GFXglyph {name}Glyphs[] PROGMEM = {{'+','.join(glyphs)+'};', f'const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bits,(GFXglyph*){name}Glyphs,32,126,{size+4}}};']
(base/'firmware/lcd43b/readout_fonts.h').write_text('\n'.join(out)+'\n')
